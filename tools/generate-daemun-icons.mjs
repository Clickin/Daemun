function indent(value, spaces = 4) {
  const pad = " ".repeat(spaces);
  return value
    .split("\n")
    .map((line) => (line ? `${pad}${line}` : line))
    .join("\n");
}

function iconGroup({ foreground = colors.foreground } = {}) {
  return [
    `<g fill="${foreground}" clip-rule="evenodd">`,
    indent(shapes.roof, 2),
    indent(shapes.roofLine, 2),
    indent(shapes.frame, 2),
    indent(shapes.doors, 2),
    indent(shapes.sill, 2),
    `</g>`,
  ].join("\n");
}

function colorSvg({ dynamic = false } = {}) {
  const start = dynamic ? "{start}" : colors.start;
  const end = dynamic ? "{end}" : colors.end;
  const foreground = dynamic ? "{foreground}" : colors.foreground;
  const gradientId = dynamic ? "{gradientId}" : "daemun-gradient";
  const fill = dynamic ? "{`url(#${gradientId})`}" : `url(#${gradientId})`;

  return [
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}" role="img" aria-label="Daemun">`,
    `  <defs>`,
    `    <linearGradient id="${gradientId}" x1="184" y1="184" x2="840" y2="840" gradientUnits="userSpaceOnUse">`,
    `      <stop offset="0" stop-color="${start}"/>`,
    `      <stop offset="1" stop-color="${end}"/>`,
    `    </linearGradient>`,
    `  </defs>`,
    `  ${shapes.background.replace("/>", ` fill="${fill}"/>`)}`,
    indent(iconGroup({ foreground }), 2),
    `</svg>`,
    "",
  ].join("\n");
}

function maskSvg() {
  return [
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}">`,
    indent(iconGroup({ foreground: "#000000" }), 2),
    `</svg>`,
    "",
  ].join("\n");
}

function wideTileSvg() {
  const scale = 150 / 1024;

  return [
    `<svg xmlns="http://www.w3.org/2000/svg" width="310" height="150" viewBox="0 0 310 150">`,
    `  <defs>`,
    `    <linearGradient id="daemun-gradient" x1="184" y1="184" x2="840" y2="840" gradientUnits="userSpaceOnUse">`,
    `      <stop offset="0" stop-color="${colors.start}"/>`,
    `      <stop offset="1" stop-color="${colors.end}"/>`,
    `    </linearGradient>`,
    `  </defs>`,
    `  <g transform="translate(80 0) scale(${scale})">`,
    `    ${shapes.background.replace("/>", ` fill="url(#daemun-gradient)"/>`)}`,
    indent(iconGroup(), 4),
    `  </g>`,
    `</svg>`,
    "",
  ].join("\n");
}

