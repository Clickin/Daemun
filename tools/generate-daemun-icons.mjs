function createIco(pngBuffers) {
  const headerSize = 6;
  const entrySize = 16;
  const count = pngBuffers.length;
  const header = Buffer.alloc(headerSize + entrySize * count);

  header.writeUInt16LE(0, 0);
  header.writeUInt16LE(1, 2);
  header.writeUInt16LE(count, 4);

  let offset = header.length;
  pngBuffers.forEach(({ buffer, size }, index) => {
    const entry = headerSize + index * entrySize;
    header.writeUInt8(size >= 256 ? 0 : size, entry);
    header.writeUInt8(size >= 256 ? 0 : size, entry + 1);
    header.writeUInt8(0, entry + 2);
    header.writeUInt8(0, entry + 3);
    header.writeUInt16LE(1, entry + 4);
    header.writeUInt16LE(32, entry + 6);
    header.writeUInt32LE(buffer.length, entry + 8);
    header.writeUInt32LE(offset, entry + 12);
    offset += buffer.length;
  });

  return Buffer.concat([header, ...pngBuffers.map(({ buffer }) => buffer)]);
}

function runSharpCli(input, output, width, height = width) {
  const pnpmArgs = [
    "dlx",
    "sharp-cli",
    "-i",
    input,
    "-o",
    output,
    "-f",
    "png",
    "resize",
    String(width),
    String(height),
  ];
  const command = process.env.npm_execpath ? process.execPath : process.platform === "win32" ? "pnpm.cmd" : "pnpm";
  const args = process.env.npm_execpath ? [process.env.npm_execpath, ...pnpmArgs] : pnpmArgs;
  const result = spawnSync(command, args, {
    cwd: root,
    shell: !process.env.npm_execpath && process.platform === "win32",
    stdio: "inherit",
  });

  if (result.error) throw result.error;
  if (result.status !== 0) {
    throw new Error(`sharp-cli failed for ${path.relative(root, output)} with exit code ${result.status}`);
  }
}

async function renderRasterAssets() {
  const squareTargets = [
    ["android-chrome-192x192.png", 192],
    ["android-chrome-512x512.png", 512],
    ["apple-touch-icon.png", 180],
    ["favicon-16x16.png", 16],
    ["favicon-32x32.png", 32],
    ["mstile-70x70.png", 70],
    ["mstile-144x144.png", 144],
    ["mstile-150x150.png", 150],
    ["mstile-310x310.png", 310],
  ];

  const tempDir = mkdtempSync(path.join(os.tmpdir(), "daemun-icons-"));
  const sourceSvg = path.join(publicDir, "daemun.svg");
  const wideSvg = path.join(tempDir, "mstile-310x150.svg");
  writeFileSync(wideSvg, wideTileSvg());

  for (const [file, size] of squareTargets) {
    runSharpCli(sourceSvg, path.join(publicDir, file), size);
  }

  runSharpCli(wideSvg, path.join(publicDir, "mstile-310x150.png"), 310, 150);

  const icoBuffers = [];
  for (const size of [16, 32, 48, 64, 128, 256]) {
    const file = path.join(tempDir, `daemun-${size}.png`);
    runSharpCli(sourceSvg, file, size);
    icoBuffers.push({
      buffer: readFileSync(file),
      size,
    });
  }
  writeFileSync(path.join(publicDir, "daemun.ico"), createIco(icoBuffers));

  rmSync(tempDir, { force: true, recursive: true });
}

async function main() {
  mkdirSync(publicDir, { recursive: true });
  mkdirSync(brandDir, { recursive: true });

  const svg = colorSvg();
  writeFileSync(path.join(publicDir, "daemun.svg"), svg);
  writeFileSync(path.join(publicDir, "favicon.svg"), svg);
  writeFileSync(path.join(publicDir, "safari-pinned-tab.svg"), maskSvg());
  writeFileSync(path.join(brandDir, "daemun-icon.jsx"), reactComponent());

  if (shouldRenderRaster) {
    await renderRasterAssets();
  } else {
    console.log("Generated SVG/icon component assets. Run `pnpm icons:raster` to refresh PNG/ICO assets.");
  }
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
